import type { Werk } from "@/lib/typen";

/**
 * Platzhalter-Werke fuer den Demo-Modus.
 *
 * Titel, Geschichten und Zitate sind erfunden. Sie stehen hier, damit
 * sich Rhythmus, Zeilenlaenge und Wirkung der Seite mit realistisch
 * langen Texten beurteilen lassen — mit Blindtext waere das nicht
 * moeglich.
 *
 * Die `palette` wird nicht angezeigt. Sie steuert das Skript
 * `scripts/gemaelde-erzeugen.mjs`, das die abstrakten Platzhalter-Bilder
 * erzeugt, damit Bild und Text zusammenpassen.
 */

export type WerkSeed = Werk & { palette: string[] };

const HOCH = { breite: 2400, hoehe: 3000 };
const QUER = { breite: 3000, hoehe: 2250 };
const QUADRAT = { breite: 2600, hoehe: 2600 };

function bilder(
  slug: string,
  format: { breite: number; hoehe: number },
  titel: string,
  detailAnzahl = 2,
) {
  return [
    {
      id: `${slug}-haupt`,
      schluessel: `/werke/${slug}.jpg`,
      art: "haupt" as const,
      altText: `${titel} — Gesamtansicht des Gemäldes`,
      breitePx: format.breite,
      hoehePx: format.hoehe,
      sortierung: 0,
    },
    ...Array.from({ length: detailAnzahl }, (_, i) => ({
      id: `${slug}-detail-${i + 1}`,
      schluessel: `/werke/${slug}-detail-${i + 1}.jpg`,
      art: "detail" as const,
      altText: `${titel} — Detailaufnahme ${i + 1}, Pinselstruktur`,
      breitePx: 1800,
      hoehePx: 1800,
      sortierung: i + 1,
    })),
  ];
}

